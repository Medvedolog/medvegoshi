ADVANCE = 12   # 8 logical pixels at 1.53x, fits the smallest existing button
HEIGHT = 15
_MAX_TEXT = 32
_EXTRA = 'Ёё«»—–…'


def _index(ch):
    u = ord(ch)
    if 32 <= u < 127:
        return u - 32
    if 0x0410 <= u < 0x0450:
        return 95 + u - 0x0410
    extra = _EXTRA.find(ch)
    return 159 + extra if extra >= 0 else -1


def supports(text):
    """True if the whole label fits the native font's alphabet and budget."""
    if not 0 < len(text) <= _MAX_TEXT:
        return False
    for ch in text:
        if _index(ch) < 0:
            return False
    return True


def _offset(i):
    i *= 2
    return _OFFSETS[i] | (_OFFSETS[i + 1] << 8)


def draw(fb, text, x, y, color, esc=1):
    """Paint only glyph ink; preserve the already scaled background."""
    advance = ADVANCE * esc
    fill = fb.fill_rect
    for ch in text[:_MAX_TEXT]:
        i = _index(ch)
        if i < 0:
            i = ord('?') - 32
        at = _offset(i)
        end = _offset(i + 1)
        while at < end:
            xy, width = _SPANS[at], _SPANS[at + 1]
            fill(x + (xy & 15) * esc, y + (xy >> 4) * esc, width * esc, esc, color)
            at += 2
        x += advance


