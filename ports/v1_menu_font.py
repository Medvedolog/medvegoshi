# Physical cell heights; unaccented capitals leave air above the baseline.
HEIGHT = 20
_HEADING_HEIGHT = 30
_BASELINE = 16
_HEADING_BASELINE = 24
_X_PAD = 3  # negative glyph bearings stored as unsigned byte offsets
_MAX_TEXT = 32
_EXTRA = 'Ёё«»—–…·'


def _index(ch):
    u = ord(ch)
    if 32 <= u < 127:
        return u - 32
    if 0x0410 <= u < 0x0450:
        return 95 + u - 0x0410
    extra = _EXTRA.find(ch)
    return 159 + extra if extra >= 0 else -1


def supports(text):
    """True if the whole label fits the native font's alphabet and budget."""
    if not 0 < len(text) <= _MAX_TEXT:
        return False
    for ch in text:
        if _index(ch) < 0:
            return False
    return True


def _glyph(ch):
    i = _index(ch)
    return i if i >= 0 else 31  # '?'


def height(esc=1):
    return _HEADING_HEIGHT if esc == 2 else HEIGHT


def baseline(esc=1):
    return _HEADING_BASELINE if esc == 2 else _BASELINE


def measure(text, esc=1):
    """Advance width in native pixels, including typographic side bearings."""
    advances = _HEADING_WIDTHS if esc == 2 else _BODY_WIDTHS
    total = 0
    for ch in text[:_MAX_TEXT]:
        total += advances[_glyph(ch)]
    return (total + 2) // 4


def _unwire(c):
    # The game's framebuf stores LCD/wire order in a native halfword.
    return ((c & 255) << 8) | (c >> 8)


def _blend(fg, bg, alpha):
    bg = _unwire(bg)
    inv = 3 - alpha
    r = ((fg >> 11) * alpha + (bg >> 11) * inv + 1) // 3
    g = (((fg >> 5) & 63) * alpha + ((bg >> 5) & 63) * inv + 1) // 3
    b = ((fg & 31) * alpha + (bg & 31) * inv + 1) // 3
    return _unwire((r << 11) | (g << 5) | b)


def draw(fb, text, x, y, color, esc=1):
    """Draw two native sizes. y is the cell top; glyph baseline never moves."""
    advances, offsets, spans = (
        (_HEADING_WIDTHS, _HEADING_OFFSETS, _HEADING_SPANS) if esc == 2 else
        (_BODY_WIDTHS, _BODY_OFFSETS, _BODY_SPANS)
    )
    native_color = _unwire(color)
    fill, pixel = fb.fill_rect, fb.pixel
    xq = x * 4
    last_bg = -1
    shade1 = shade2 = 0
    for ch in text[:_MAX_TEXT]:
        i = _glyph(ch)
        q = i * 2
        at = offsets[q] | (offsets[q + 1] << 8)
        end = offsets[q + 2] | (offsets[q + 3] << 8)
        x_origin = (xq + 2) // 4 - _X_PAD
        while at < end:
            # Packed 16-bit span: 5 y / 2 coverage / 5 x / 4 length-1.
            hi, lo = spans[at], spans[at + 1]
            yy = y + (hi >> 3)
            xx = x_origin + (((hi & 1) << 4) | (lo >> 4))
            alpha = (hi >> 1) & 3
            length = (lo & 15) + 1
            if alpha == 3:
                fill(xx, yy, length, 1, color)
            else:
                for px in range(xx, xx + length):
                    bg = pixel(px, yy)
                    if bg is not None:
                        if bg != last_bg:
                            last_bg = bg
                            shade1 = _blend(native_color, bg, 1)
                            shade2 = _blend(native_color, bg, 2)
                        pixel(px, yy, shade1 if alpha == 1 else shade2)
            at += 2
        xq += advances[i]


